-- On supprime tout pour repartir sur une base propre
DROP USER C##DWH CASCADE;

CREATE USER C##DWH IDENTIFIED BY dwh123;

-- Droits de base pour la connexion et ODI
GRANT CONNECT, RESOURCE, CREATE VIEW, UNLIMITED TABLESPACE TO C##DWH;

-- DROIT CRUCIAL : Permettre au DWH de lire les tables de l'ODS pour l'ETL
GRANT SELECT ANY TABLE TO C##DWH;

-- ==========================================================
-- 2. CRÉATION DES TABLES DE DIMENSIONS (Le Schéma en Étoile)
-- ==========================================================

-- Table DIMTRACK (Dénormalisée : contient Album et Artiste)
CREATE TABLE C##DWH.DIMTRACK (
    TRACKID NUMBER PRIMARY KEY,
    TRACKNAME VARCHAR2(200),
    ALBUMTITLE VARCHAR2(200),
    ARTISTNAME VARCHAR2(200),
    MEDIATYPE VARCHAR2(100),
    GENRE VARCHAR2(100),
    UNITPRICE NUMBER(10,2)
);

-- Table DIMCUSTOMER (Dénormalisée : contient le nom du support)
CREATE TABLE C##DWH.DIMCUSTOMER (
    CUSTOMERID NUMBER PRIMARY KEY,
    FIRSTNAME VARCHAR2(100),
    LASTNAME VARCHAR2(100),
    CITY VARCHAR2(100),
    COUNTRY VARCHAR2(100),
    SUPPORTREPNAME VARCHAR2(200)
);

-- Table DIMEMPLOYEE (Hiérarchie interne)
CREATE TABLE C##DWH.DIMEMPLOYEE (
    EMPLOYEEID NUMBER PRIMARY KEY,
    LASTNAME VARCHAR2(100),
    FIRSTNAME VARCHAR2(100),
    TITLE VARCHAR2(100),
    CITY VARCHAR2(100)
);

-- Table DIMINVOICE (Entêtes de ventes)
CREATE TABLE C##DWH.DIMINVOICE (
    INVOICEID NUMBER PRIMARY KEY,
    INVOICEDATE DATE,
    BILLINGCITY VARCHAR2(100),
    BILLINGCOUNTRY VARCHAR2(100)
);

-- Table DIMPLAYLIST (Référentiel des Playlists)
CREATE TABLE C##DWH.DIMPLAYLIST (
    PLAYLISTID NUMBER PRIMARY KEY,
    NAME VARCHAR2(200)
);

-- Table DIMDATE (Pour les analyses temporelles)
CREATE TABLE C##DWH.DIMDATE (
    DATE_KEY DATE PRIMARY KEY,
    ANNEE NUMBER,
    MOIS NUMBER,
    JOUR_NOM VARCHAR2(20),
    TRIMESTRE NUMBER
);

-- ==========================================================
-- 3. TABLES DE LIAISONS ET FAITS (Avec Relations/FK)
-- ==========================================================

-- Table BRIDGEPLAYLISTTRACK (Gère la relation N-N entre Playlist et Musique)
CREATE TABLE C##DWH.BRIDGEPLAYLISTTRACK (
    PLAYLISTID NUMBER,
    TRACKID NUMBER,
    CONSTRAINT PK_BRIDGE_PT PRIMARY KEY (PLAYLISTID, TRACKID),
    CONSTRAINT FK_BRIDGE_PLAYLIST FOREIGN KEY (PLAYLISTID) REFERENCES C##DWH.DIMPLAYLIST(PLAYLISTID),
    CONSTRAINT FK_BRIDGE_TRACK FOREIGN KEY (TRACKID) REFERENCES C##DWH.DIMTRACK(TRACKID)
);

-- Table de Faits FACTSALES (Cœur de l'analyse)
CREATE TABLE C##DWH.FACTSALES (
    SALESID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    INVOICEID NUMBER,
    TRACKID NUMBER,
    CUSTOMERID NUMBER,
    UNITPRICE NUMBER(10,2),
    QUANTITY NUMBER,
    TOTALAMOUNT NUMBER(10,2),
    -- Définition des relations (Clés étrangères)
    CONSTRAINT FK_FACT_INVOICE FOREIGN KEY (INVOICEID) REFERENCES C##DWH.DIMINVOICE(INVOICEID),
    CONSTRAINT FK_FACT_TRACK FOREIGN KEY (TRACKID) REFERENCES C##DWH.DIMTRACK(TRACKID),
    CONSTRAINT FK_FACT_CUSTOMER FOREIGN KEY (CUSTOMERID) REFERENCES C##DWH.DIMCUSTOMER(CUSTOMERID)
);

